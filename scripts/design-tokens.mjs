// Regenerate the native theme, UTS color values and Sass API from one source.
import fs from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const app = fileURLToPath(new URL('../visitor-app/', import.meta.url))
const tokens = JSON.parse(fs.readFileSync(path.join(app, 'design/tokens.json'), 'utf8'))
function output(relative, content) {
  const file = path.join(app, relative)
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== content) throw new Error('Regenerate ' + relative)
  } else {
    fs.writeFileSync(file, content)
  }
}
const entries = Object.entries(tokens.color)
// The two backend-served avatar documents also need the mobile palette.
const stageColors = index => entries.map(([key, values]) => `  --sg-${key}: ${values[index]};`).join('\n')
output('../server/src/web/digital-human/stage-tokens.css', [
  '/* Generated by node scripts/design-tokens.mjs */',
  ':root {', '  color-scheme: light;', stageColors(0), '}',
  ':root[data-theme="dark"] {', '  color-scheme: dark;', stageColors(1), '}',
  '@media (prefers-color-scheme: dark) {', '  :root:not([data-theme]) {',
  '    color-scheme: dark;', stageColors(1).replace(/^/gm, '  '), '  }', '}', ''
].join('\n'))
const scss = ['// Generated by node scripts/design-tokens.mjs']
for (const [name, [light]] of entries) {
  scss.push(`$sg-base-${name}: ${light};`, `$sg-${name}: var(--sg-${name}, $sg-base-${name});`)
}
for (const [i, px] of tokens.space.entries()) scss.push(`$sg-space-${i + 1}: ${px}px;`)
for (const [name, px] of Object.entries(tokens.radius)) scss.push(`$sg-radius-${name}: ${px}px;`)
for (const [name, px] of Object.entries(tokens.type)) scss.push(`$sg-type-${name}: var(--sg-type-${name}, ${px}px);`)
scss.push(`$sg-touch: ${tokens.touch}px;`)
for (const [name, px] of Object.entries(tokens.tabBar)) scss.push(`$sg-tab-${name}: ${px}px;`)
const motion = tokens.motion
const durations = ['immediate', 'fast', 'normal', 'medium', 'sheet', 'page']
for (const name of durations) scss.push(`$sg-duration-${name}: ${motion[name]}ms;`)
scss.push(`$sg-motion-delay: ${motion.delay}ms;`, `$sg-press-scale: ${motion.pressScale};`,
  `$sg-pressed-opacity: ${motion.pressedOpacity};`, `$sg-translation: ${motion.translation}px;`)
for (const [name, curve] of Object.entries(motion.easing)) scss.push(`$sg-ease-${name}: ${curve};`)
for (const [name, recipe] of Object.entries(motion.transition)) {
  if (!durations.includes(recipe.duration) || !Object.hasOwn(motion.easing, recipe.easing)) {
    throw new Error('Unknown duration or easing in transition ' + name)
  }
  scss.push(`@mixin sg-transition-${name} {`, `  transition-property: ${recipe.property};`,
    `  transition-duration: $sg-duration-${recipe.duration};`, `  transition-timing-function: $sg-ease-${recipe.easing};`,
    '  transition-delay: $sg-motion-delay;', '}')
}
scss.push('@mixin sg-themes {')
for (const [index, theme] of ['light', 'dark'].entries()) {
  scss.push(`  .sg-${theme} {`, ...entries.map(([name, values]) => `    --sg-${name}: ${values[index]};`), '  }')
}
scss.push('  .sg-large-type {')
for (const [name, px] of Object.entries(tokens.type)) scss.push(`    --sg-type-${name}: ${Math.round(px * tokens.largeTypeScale)}px;`)
scss.push('  }', '}')
output('design/tokens.scss', scss.join('\n') + '\n')
const uts = ['// Generated by node scripts/design-tokens.mjs']
for (const [i, name] of ['lightPalette', 'darkPalette'].entries()) {
  uts.push(`export const ${name} : UTSJSONObject = {`, entries.map(([key, vals]) => `  '${key}': '${vals[i]}'`).join(',\n'), '}')
}
uts.push(`export const headerGap = ${tokens.space[2]}`, `export const mapHeaderGap = ${tokens.space[1]}`, `export const touchSize = ${tokens.touch}`, `export const buttonTextSize = ${tokens.type.button}`, `export const largeButtonTextSize = ${Math.round(tokens.type.button * tokens.largeTypeScale)}`, `export const pressDuration = ${motion.fast}`, `export const feedbackDelay = ${motion.delay}`, `export const sheetDuration = ${motion.sheet}`)
uts.push(`export const tabTransitionDuration = ${motion.normal}`)
uts.push(`export const guideStageMinHeight = ${tokens.guideStage.minHeight}`, `export const guideStageMaxHeight = ${tokens.guideStage.maxHeight}`, `export const guideStageWindowFraction = ${tokens.guideStage.windowFraction}`)
output('design/palette.uts', uts.join('\n') + '\n')
const orb = tokens.orb
output('design/orb-tokens.uts', ['// Generated by node scripts/design-tokens.mjs',
  ...['size', 'stageHeight', 'tickMs', 'attackMs', 'releaseMs', 'rmsGain', 'listenCycleMs', 'speakCycleMs'].map(key =>
    `export const orb${key[0].toUpperCase() + key.slice(1)} = ${orb[key]}`), ''
].join('\n'))
const native = {}
for (const [i, theme] of ['light','dark'].entries()) {
  native[theme] = { tabMuted: tokens.color.muted[i], tabActive: tokens.color.primary[i], surface: tokens.color.surface[i], background: tokens.color.background[i], navText: i ? 'white' : 'black', tabBorder: i ? 'white' : 'black' }
  for (const key of ['home','map','ai','trip','profile']) {
    native[theme][key+'Icon'] = 'static/tabbar/'+key+(i ? '-dark' : '')+'.png'
    native[theme][key+'Selected'] = 'static/tabbar/'+key+'-active'+(i ? '-dark' : '')+'.png'
  }
}
output('theme.json', JSON.stringify(native, null, 2) + '\n')
